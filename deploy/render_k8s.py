def _inject(text: str, marker: str, block: str) -> str:
    """Replace each line that is exactly `marker` (ignoring surrounding
    whitespace) with `block`, re-indented to that marker line's indentation.

    This runs AFTER textwrap.dedent so a multi-line block can be spliced into a
    dedented template without its own indentation corrupting the dedent's common
    -prefix calculation (the bug that flattened the Cloud SQL proxy sidecar)."""
    lines = []
    for line in text.splitlines():
        if line.strip() == marker:
            indent = line[: len(line) - len(line.lstrip())]
            lines.append(textwrap.indent(textwrap.dedent(block).rstrip("\n"), indent))
        else:
            lines.append(line)
    return "\n".join(lines) + "\n"


def load_cfg() -> dict[str, str]:
    cfg: dict[str, str] = {}
    for line in CFG.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        cfg[k.strip()] = v.strip()
    return cfg


