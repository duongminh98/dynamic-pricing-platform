#!/usr/bin/env python3
"""Render GKE manifests for the Dynamic Pricing Platform from a single service
inventory. Deterministic + idempotent: re-running overwrites deploy/k8s/*.yaml.

Design choices baked in (match GCP_DEPLOYMENT.md §4):
  * Every app service is a private ClusterIP Deployment — only Kong is exposed.
  * Cloud SQL is reached via the **Cloud SQL Auth Proxy sidecar** on 127.0.0.1
    (no private-IP wiring needed for staging; the proxy uses Workload Identity).
  * Secrets (DB password, RabbitMQ, VNPAY) come from a k8s Secret `dpp-secrets`
    synced from Secret Manager (created by provision.sh, not committed).
  * Flyway/Alembic run as pre-deploy Jobs; serving pods set *_FLYWAY_ENABLED=false
    / RUN_MIGRATIONS=false.
  * Background workers (outbox relay + consumers) => minReplicas>=1, no
    scale-to-zero (GKE has no CPU throttling, so this "just works").

Usage: python deploy/render_k8s.py   (reads deploy/config.env)
"""
