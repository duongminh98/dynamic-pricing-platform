def render_env(env_lines: list[tuple[str, dict]]) -> str:
    out = []
    for name, spec in env_lines:
        if "value" in spec:
            out.append(f"- name: {name}\n  value: \"{spec['value']}\"")
        elif "secret" in spec:
            out.append(
                f"- name: {name}\n  valueFrom:\n    secretKeyRef:\n"
                f"      name: dpp-secrets\n      key: {spec['secret']}"
            )
    return "\n".join(out)


